function getCartTotals(cart = getCart()) {
    const totals = normalizeCart(cart).reduce((result, item) => {
        const product = getProduct(item.id);
        if (!product) return result;
        result.quantity += item.quantity;
        result.subtotal += getUnitPrice(product) * item.quantity;
        return result;
    }, { quantity: 0, subtotal: 0 });
    let hasDiscount = false;
    let rule = null, discountCode = '';
    try {
        discountCode = localStorage.getItem(DISCOUNT_KEY) || '';
        rule = JSON.parse(localStorage.getItem('web2_discount_rule') || 'null');
        if (!rule && discountCode === DISCOUNT_CODE) rule = {code:DISCOUNT_CODE,type:'percent',value:10};
        hasDiscount = rule?.code === discountCode && ['percent','fixed'].includes(rule.type) && Number.isSafeInteger(rule.value) && rule.value > 0 && (rule.type !== 'percent' || rule.value <= 100);
    } catch {}
    const discount = hasDiscount ? Math.min(totals.subtotal, rule.type === 'percent' ? Math.round(totals.subtotal * rule.value / 100) : rule.value) : 0;
    const settings=window.Web2Site?.settings;
    const shippingCost=settings&&(settings.freeShippingThreshold===null||totals.subtotal-discount<settings.freeShippingThreshold)?settings.shippingCost:0;
    return {
        ...totals,shippingCost,
        price: totals.subtotal - discount + shippingCost,
        discount,
        hasDiscount,
        discountCode: hasDiscount ? discountCode : ''
    };
}

