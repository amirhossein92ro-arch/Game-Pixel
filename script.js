async function fetchProductsSnapshot() {
    try {
        const response = await fetch(window.Web2Config?.apiUrl(PRODUCT_API_BASE) || PRODUCT_API_BASE, { cache: 'no-store', credentials: 'include', headers: { Accept: "application/json" } });
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        const payload = await response.json();
        const apiProducts = Array.isArray(payload) ? payload : payload.products;
        if (!Array.isArray(apiProducts)) throw new Error("Invalid products payload");
        const merged = mergeProducts(apiProducts);
        if (merged.length !== apiProducts.length) throw new Error('Invalid or duplicate product IDs in API response');
        const previous = mergeProducts(readProductCache('gaming_store_products_unresolved'), products, readProductCache(PRODUCTS_KEY), readProductCache(PRODUCT_FALLBACK_KEY), migrateLegacyProducts());
        const unsynced = previous.filter(item => !merged.some(product => product.id === item.id));
        if (unsynced.length) cacheProducts('gaming_store_products_unresolved', mergeProducts(readProductCache('gaming_store_products_unresolved'), unsynced));
        productIdAliases.clear();
        for (const old of unsynced) {
            const matches = merged.filter(product => product.name === old.name && product.brand === old.brand);
            if (matches.length === 1) productIdAliases.set(old.id, matches[0].id);
        }
        for (const item of previous) {
            if (!merged.some(product => product.id === item.id)) console.warn('Missing backend product:', { ID: item.id, Name: item.name });
        }
        migrateCachedCartIds(previous, merged);
        productDetailLookups.clear();
        products = merged.filter(p => p.status !== 'inactive');
        productsSource = 'api';
        cacheProducts(PRODUCTS_KEY, products);
        cacheProducts(PRODUCT_FALLBACK_KEY, products);
        // Rebuild old product-only caches from the authoritative snapshot. Leave
        // cart, account and session storage untouched; never guess replacement IDs.
        for (const key of LEGACY_PRODUCT_KEYS) {
            try { if (localStorage.getItem(key) !== null) cacheProducts(key, products); } catch {}
        }
        console.log(`[products] API محصولات: بارگذاری ${apiProducts.length} محصول، ادغام: ${merged.length}`);
        return products;
    } catch (error) {
        productsError = error;
        console.error("[products] بارگذاری API:", error);
        // A failed refresh must keep the last authoritative in-memory snapshot.
        if (productsSource !== 'api') products = getProducts();
        showToast('ارتباط با سرور محصولات برقرار نشد؛ اطلاعات ذخیره‌شده نمایش داده می‌شود.', 'error');
        console.warn(`[products] بارگذاری محصولات از حافظه: ${products.length} محصول`);
        return products;
    }
}

function migrateCachedCartIds(previous, authoritative) {
    // Match only one exact name + brand; never guess from price or array position.
    for (const key of [CART_KEY, 'cart']) {
        try {
            const cart = JSON.parse(localStorage.getItem(key));
            if (!Array.isArray(cart)) continue;
            let changed = false;
            const unresolved = [];
            const migrated = cart.map(item => {
                if (!item || normalizeProductId(item.id) === null || authoritative.some(p => p.id === String(item.id))) return item;
                const old = previous.find(p => p.id === String(item.id));
                const matches = old ? authoritative.filter(p => p.name === old.name && p.brand === old.brand) : [];
                if (matches.length === 1) { changed = true; return { ...item, id: matches[0].id }; }
                unresolved.push({ ...item, product: old || null });
                return item;
            });
            if (changed) cacheProducts(key, migrated);
            if (unresolved.length) {
                const saved = JSON.parse(localStorage.getItem('web2_cart_unresolved') || '[]');
                const retained = new Map((Array.isArray(saved) ? saved : []).map(item => [String(item.id), item]));
                unresolved.forEach(item => retained.set(String(item.id), item));
                cacheProducts('web2_cart_unresolved', [...retained.values()]);
            }
        } catch { /* Storage failure must not erase the original cart. */ }
    }
}

// A catalog omission is not proof of deletion. Only a real single-product 404 is.
async function resolveMissingProduct(id) {
    if (productDetailLookups.has(id)) return productDetailLookups.get(id).promise;
    const state = { status: 'loading', promise: null };
    productDetailLookups.set(id, state);
    state.promise = (async () => {
        try {
            const path = PRODUCT_API_BASE + '/' + encodeURIComponent(id);
            const response = await fetch(window.Web2Config?.apiUrl(path) || path, { cache: 'no-store', credentials: 'include', headers: { Accept: 'application/json' } });
            const payload = await response.json();
            if (response.status === 404 && payload && typeof payload.error === 'string') {
                const canonicalId = productIdAliases.get(id);
                if (canonicalId && getProduct(canonicalId)) {
                    const canonicalPath = PRODUCT_API_BASE + '/' + encodeURIComponent(canonicalId);
                    const canonicalResponse = await fetch(window.Web2Config?.apiUrl(canonicalPath) || canonicalPath, { cache: 'no-store', credentials: 'include', headers: { Accept: 'application/json' } });
                    if (!canonicalResponse.ok) throw new Error(`HTTP ${canonicalResponse.status}`);
                    const canonical = normalizeProduct(await canonicalResponse.json());
                    if (!canonical || canonical.id !== canonicalId) throw new Error('Invalid canonical product response');
                    products = mergeProducts(products, [canonical]);
                    const url = new URL(window.location.href);
                    url.searchParams.set('id', canonicalId);
                    window.history.replaceState(null, '', url.href);
                    state.status = 'found';
                    return;
                }
                state.status = 'not-found'; return;
            }
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            const product = normalizeProduct(payload.product || payload);
            if (!product || product.id !== id || product.status === 'inactive') throw new Error('Invalid single-product response');
            products = mergeProducts(products, [product]);
            cacheProducts(PRODUCTS_KEY, products);
            cacheProducts(PRODUCT_FALLBACK_KEY, products);
            state.status = 'found';
        } catch (error) { state.status = 'error'; state.error = error; console.error('[products] Single-product API:', id, error); }
    })();
    return state.promise;
}

