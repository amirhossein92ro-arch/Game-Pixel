function addToCart(productId) {
    if (!getCurrentUser()) {
        openAuthModal("برای افزودن محصول به سبد خرید، ابتدا وارد حساب کاربری شوید.");
        return;
    }
    const product = getProduct(productId);
    if (!product) {
        showToast("محصول موردنظر پیدا نشد.", "error");
        return;
    }
    if (!normalizeCart([{ id: product.id, quantity: 1 }]).length) {
        showToast("این محصول در حال حاضر موجود نیست.", "error");
        return;
    }

    const cart = getCart();
    const cartItem = cart.find((item) => String(item.id) === String(product.id));

    if (cartItem) {
        if (cartItem.quantity >= Math.floor(Number(product.stock))) {
            showToast("بیشتر از موجودی محصول نمی‌توان اضافه کرد.", "error");
            return;
        }
        cartItem.quantity += 1;
    } else {
        cart.push({ id: String(product.id), quantity: 1 });
    }

    if (!saveCart(cart)) return;
    showToast(`${product.name} به سبد خرید اضافه شد.`);

    const button = [...document.querySelectorAll('[data-add-to-cart]')].find(button => button.dataset.addToCart === String(product.id));
    if (button) {
        const originalContent = button.dataset.cartOriginalContent || button.innerHTML;
        button.dataset.cartOriginalContent = originalContent;
        window.clearTimeout(button.cartFeedbackTimer);
        button.innerHTML = '<i class="fa-solid fa-check"></i> به سبد اضافه شد';
        button.cartFeedbackTimer = window.setTimeout(() => {
            button.innerHTML = originalContent;
            delete button.dataset.cartOriginalContent;
        }, 1400);
    }
}

