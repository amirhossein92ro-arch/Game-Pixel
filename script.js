let checkoutRequestKey = typeof crypto !== "undefined" && crypto.randomUUID ? crypto.randomUUID() : "";
let checkoutRequestFingerprint = '';
async function getCheckoutRequestKey(payload) {
    const fingerprint = JSON.stringify(payload);
    if (fingerprint === checkoutRequestFingerprint && checkoutRequestKey) return checkoutRequestKey;
    try {
        const stored = JSON.parse(sessionStorage.getItem('web2_pending_checkout') || 'null');
        if (stored?.fingerprint === fingerprint && stored.key) {
            checkoutRequestFingerprint = fingerprint; checkoutRequestKey = stored.key; return stored.key;
        }
    } catch {}
    checkoutRequestFingerprint = fingerprint; checkoutRequestKey = crypto.randomUUID();
    try { sessionStorage.setItem('web2_pending_checkout', JSON.stringify({fingerprint,key:checkoutRequestKey})); } catch {}
    return checkoutRequestKey;
}
