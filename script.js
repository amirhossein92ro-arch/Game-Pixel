function readCheckoutData() {
    try {
        const stored = JSON.parse(localStorage.getItem(CHECKOUT_DATA_KEY) || "{}");
        if (!stored || typeof stored !== "object" || Array.isArray(stored)) return {};

        if (!stored.recipient && (stored.recipientName || stored.recipientPhone || stored.recipientAddress)) {
            stored.recipient = {
                name: stored.recipientName || "",
                phone: stored.recipientPhone || "",
                address: stored.recipientAddress || ""
            };
        }
        return stored;
    } catch {
        return {};
    }
}

function saveCheckoutData(patch) {
    const next = { ...readCheckoutData(), ...patch, updatedAt: new Date().toISOString() };
    try { localStorage.setItem(CHECKOUT_DATA_KEY, JSON.stringify(next)); } catch {}
    return next;
}

