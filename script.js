// IDs are opaque keys. Never infer identity from a number or generate it here.
function normalizeProductId(value) {
    if (typeof value === 'number') return Number.isSafeInteger(value) && value > 0 ? String(value) : null;
    if (typeof value !== 'string' || !value.trim() || value !== value.trim()) return null;
    if (/[\u0000-\u001f\u007f]/.test(value)) return null;
    return value;
}
function normalizeProduct(item) {
    if (!item || typeof item !== "object") return null;

    const id = normalizeProductId(item.id);
    if (id === null) return null;
    const price = Number(item.price);
    const stockRaw = Number(item.stock);
    const ratingRaw = Number(item.rating);
    const reviewsRaw = Number(item.reviews);

    let features = [];
    if (Array.isArray(item.features)) {
        features = item.features.map((feature) => String(feature)).filter(Boolean);
    } else if (item.specs && typeof item.specs === "object") {
        features = Object.entries(item.specs).map(([key, value]) => `${key}: ${value}`);
    } else if (item.specifications && typeof item.specifications === "object") {
        features = Object.entries(item.specifications).map(([key, value]) => `${key}: ${value}`);
    }

    const description = String(item.description ?? item.shortDescription ?? "").trim();
    const shortDescription = String(item.shortDescription ?? item.description ?? description).trim();
    const name = String(item.name ?? item.title ?? "محصول بدون نام").trim();
    const category = normalizeProductCategory(item.category, name);

    return {
        id,
        featured:item.featured,isNew:item.isNew,bestSeller:item.bestSeller,
        name,
        image: getProductImage(item.image, category),
        brand: String(item.brand ?? "WEB 2").trim(),
        icon: normalizeIcon(item.icon ?? item.image),
        accent: normalizeAccent(item.accent),
        tag: String(item.tag ?? "محصول").trim(),
        price: Number.isSafeInteger(price) && price > 0 ? price : 0,
        discount: Number.isFinite(Number(item.discount)) ? Math.min(99, Math.max(0, Number(item.discount))) : 0,
        stock: Number.isFinite(stockRaw) && stockRaw >= 0 ? Math.floor(stockRaw) : 0,
        rating: Number.isFinite(ratingRaw) && ratingRaw > 0 ? ratingRaw : 5,
        reviews: Number.isFinite(reviewsRaw) && reviewsRaw >= 0 ? reviewsRaw : 0,
        shortDescription,
        description,
        features,
        guarantee: String(item.guarantee ?? "گارانتی فروشگاه").trim(),
        category,
        status: item.status === "inactive" ? "inactive" : "active",
        createdAt: item.createdAt || "",
        updatedAt: item.updatedAt || ""
    };
}

function mergeProducts(...lists) {
    const merged = new Map();
    lists.flat().forEach((item) => {
        const normalized = normalizeProduct(item);
        if (normalized) merged.set(String(normalized.id), { ...(merged.get(String(normalized.id)) || {}), ...normalized });
    });
    return [...merged.values()];
}

// اگر داده‌ها قبلاً با کلید دیگری ذخیره شده بودند، آن‌ها را پیدا و منتقل می‌کند (بدون حذف کلید قدیمی).
function migrateLegacyProducts() {
    const migrated = [];
    for (const legacyKey of LEGACY_PRODUCT_KEYS) {
        try {
            const legacy = JSON.parse(localStorage.getItem(legacyKey));
            if (Array.isArray(legacy) && legacy.length) {
                // Only recognizable shipped demos may recover a missing legacy ID.
                const valid = mergeProducts(legacy.map(item => {
                    if (!item || item.id != null && item.id !== '') return item;
                    const demo = defaultProducts.find(demo => demo.name === item.name && demo.brand === item.brand);
                    return demo ? { ...item, id: String(demo.id) } : item;
                })).filter(p => p.status !== 'inactive' && p.price > 0);
                if (valid.length) migrated.push(...valid);
            }
        } catch {
            continue;
        }
    }
    return mergeProducts(migrated);
}

// Only nonempty, usable fallback data can replace/extend a local catalog.
function readProductCache(key) {
    try {
        const value = JSON.parse(localStorage.getItem(key));
        if (Array.isArray(value)) return mergeProducts(value).filter(p => p.status !== 'inactive' && p.price > 0);
    } catch {}
    return [];
}

function getProducts() {
    // Once received, the server snapshot cannot be replaced by another tab's cache.
    if (productsSource === 'api') return products;
    const snapshot = readProductCache(PRODUCT_FALLBACK_KEY);
    const stored = readProductCache(PRODUCTS_KEY);
    // Recover every valid stored ID; the API cache wins over older local values.
    const legacy = migrateLegacyProducts();
    const fallback = mergeProducts(
        !products.length && !stored.length && !snapshot.length ? defaultProducts : [],
        legacy, stored, snapshot
    );
    if (fallback.length) {
        // Keep locally valid IDs missing from an incomplete fallback snapshot.
        products = mergeProducts(fallback, products);
        productsSource = stored.length || snapshot.length || legacy.length ? 'cache' : 'default';
        cacheProducts(PRODUCTS_KEY, products);
    } else if (!products.length) {
        products = mergeProducts(defaultProducts, migrateLegacyProducts());
        productsSource = 'default';
        cacheProducts(PRODUCTS_KEY, products);
    }
    productsLoaded = true;
    return products;
}

